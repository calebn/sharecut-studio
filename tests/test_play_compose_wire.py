_WINDOW_MESSAGE = "timeline_end must be after timeline_start"
_DETAIL_MESSAGE = "detail must be summary, full, or visual. Pass one of those levels."
_BAD_CALLS = {
    "end-before-start": (3.0, 1.0, {}, "invalid_range", _WINDOW_MESSAGE),
    "end-equals-start": (1.0, 1.0, {}, "invalid_range", _WINDOW_MESSAGE),
    "unknown-detail": (0.0, 1.0, {"detail": "nope"}, "invalid_detail", _DETAIL_MESSAGE),
    "empty-detail": (0.0, 1.0, {"detail": ""}, "invalid_detail", _DETAIL_MESSAGE),
    "capitalised-detail": (0.0, 1.0, {"detail": "FULL"}, "invalid_detail", _DETAIL_MESSAGE),
    "window-checked-before-detail": (
        2.0,
        1.0,
        {"detail": "nope"},
        "invalid_range",
        _WINDOW_MESSAGE,
    ),
}


@pytest.mark.parametrize("surface", ["service", "mcp"])
@pytest.mark.parametrize("name", list(_BAD_CALLS))
def test_a_bad_request_raises_a_coded_value_error(tmp_path, name, surface):
    from podcast_mcp.util.coded_error import CodedValueError

    start, end, kwargs, code, message = _BAD_CALLS[name]
    ws = CASES["pair-summary"].build(tmp_path)
    with pytest.raises(CodedValueError) as raised:
        {"service": run_service, "mcp": run_mcp}[surface](ws, start, end, **kwargs)
    assert type(raised.value) is CodedValueError
    assert (raised.value.code, str(raised.value)) == (code, message)
    assert isinstance(raised.value, ValueError)


@pytest.mark.parametrize("name", list(_BAD_CALLS))
def test_a_bad_request_exits_the_cli_with_the_coded_message(tmp_path, name):
    start, end, kwargs, code, message = _BAD_CALLS[name]
    ws = CASES["pair-summary"].build(tmp_path)
    args = ["play", "context", "--project", str(ws.path)]
    args += ["--start", repr(start), "--end", repr(end)]
    if "detail" in kwargs:
        args += ["--detail", kwargs["detail"]]
    result = CliRunner().invoke(app, args)
    assert result.exit_code == 1
    assert result.output == (
        f"Error: {message} (code {code}) (set PODCAST_DEBUG=1 for the traceback)\n"
    )


