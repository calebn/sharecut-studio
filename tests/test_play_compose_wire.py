def test_a_missing_project_is_reported_by_the_mcp_tool_and_the_cli(tmp_path):
    from podcast_mcp.mcp.tools.play import audition_context_tool
    from podcast_mcp.util.coded_error import CodedFileNotFoundError

    missing = tmp_path / "nope.sharecut"
    with pytest.raises(CodedFileNotFoundError) as raised:
        audition_context_tool(str(missing), 0.0, 1.0)
    assert (raised.value.code, str(raised.value)) == (
        "project_not_found",
        f"Project not found: {missing}",
    )
    args = ["play", "context", "--project", str(missing), "--start", "0", "--end", "1"]
    result = CliRunner().invoke(app, args)
    assert result.exit_code == 1
    assert result.output == (
        f"Error: Project not found: {missing} (code project_not_found) "
        "(set PODCAST_DEBUG=1 for the traceback)\n"
    )
