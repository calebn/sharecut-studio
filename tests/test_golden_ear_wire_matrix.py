@pytest.mark.parametrize("name", sorted(NONDET_EXPECTED))
def test_unseeded_build_assigns_each_pair_both_files(name, runs):
    for pair in runs(name)["snapshot"]["key"]["pairs"]:
        assert sorted([pair["leave_file"], pair["edit_file"]]) == ["1.wav", "2.wav"]


