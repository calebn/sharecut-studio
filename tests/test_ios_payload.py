def contract(**changes):
    raw = copy.deepcopy(CONTRACT)
    raw.update(changes)
    return payload.parse_contract(raw)


def plan_of(contract_value=None):
    return payload.plan_packages(
        payload.parse_export(EXPORT), payload.parse_lock(LOCK), contract_value or contract()
    )


def classes(plan):
    return {pkg.name: pkg.package_class.value for pkg in plan.packages}


