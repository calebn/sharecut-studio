def test_the_digest_ignores_order_and_changes_with_any_input() -> None:
    base = {"contract": "1", "uv.lock": "2", "sdk": "iphoneos"}
    reordered = {"sdk": "iphoneos", "uv.lock": "2", "contract": "1"}
    assert payload.digest_inputs(base) == payload.digest_inputs(reordered)
    assert payload.digest_inputs(base) == DIGEST
    assert payload.digest_inputs({**base, "sdk": "iphonesimulator"}) != payload.digest_inputs(base)


def test_the_tree_digest_follows_content_not_bytecode(tmp_path: Path) -> None:
    (tmp_path / "pkg").mkdir()
    (tmp_path / "pkg" / "a.py").write_text("x = 1\n")
    first = payload.tree_digest(tmp_path)
    (tmp_path / "pkg" / "__pycache__").mkdir()
    (tmp_path / "pkg" / "__pycache__" / "a.pyc").write_bytes(b"junk")
    assert payload.tree_digest(tmp_path) == first
    (tmp_path / "pkg" / "a.py").write_text("x = 2\n")
    assert payload.tree_digest(tmp_path) != first


def macho(platform: int | None) -> bytes:
    commands = b""
    if platform is not None:
        commands = struct.pack("<IIIIIII", 0x32, 24, platform, 0, 0, 0, 0)
    header = struct.pack(
        "<IiiIIIII", 0xFEEDFACF, 0x0100000C, 0, 6, 1 if commands else 0, len(commands), 0, 0
    )
    return header + commands


def test_the_macho_platform_is_read_from_the_build_version_command() -> None:
    assert payload.macho_platform(macho(7)) == 7
    assert payload.macho_platform(macho(2)) == 2
    assert payload.macho_platform(macho(None)) is None
    assert payload.macho_platform(b"not a binary at all, just text padding " * 2) is None


def test_the_site_packages_check_refuses_static_libraries_and_foreign_slices(
    tmp_path: Path,
) -> None:
    sdk = contract().sdks["iphonesimulator"]
    (tmp_path / "good.so").write_bytes(macho(7))
    payload.check_site_packages(tmp_path, sdk)
    (tmp_path / "device.so").write_bytes(macho(2))
    (tmp_path / "libx.a").write_bytes(b"!<arch>\n")
    with pytest.raises(payload.PayloadError) as caught:
        payload.check_site_packages(tmp_path, sdk)
    assert "device.so: Mach-O platform 2" in str(caught.value)
    assert "libx.a: static library" in str(caught.value)


def wheel_bytes(files: dict[str, bytes]) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, data in files.items():
            archive.writestr(name, data)
    return buffer.getvalue()


def test_a_wheel_unpacks_with_its_data_purelib_merged(tmp_path: Path) -> None:
    wheel = tmp_path / "pkg-1-py3-none-any.whl"
    wheel.write_bytes(
        wheel_bytes(
            {
                "pkg/__init__.py": b"A = 1\n",
                "pkg-1.dist-info/METADATA": b"Name: pkg\n",
                "pkg-1.data/purelib/extra.py": b"B = 2\n",
                "pkg-1.data/scripts/tool": b"#!/bin/sh\n",
            }
        )
    )
    site = tmp_path / "site"
    site.mkdir()
    payload.extract_wheel(wheel, site)
    assert sorted(str(p.relative_to(site)) for p in site.rglob("*") if p.is_file()) == [
        "extra.py",
        "pkg-1.dist-info/METADATA",
        "pkg/__init__.py",
    ]


