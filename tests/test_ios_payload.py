def test_the_committed_contract_and_lock_agree() -> None:
    """Every package the lock keeps on iOS has a class, and no contract row is stale."""
    loaded = payload.load_contract()
    _, plan = payload.load_plan(loaded)
    payload.check_engine_requirements(
        plan, payload.engine_requirements(), loaded.marker_environment
    )
    kept = {
        pkg.name: pkg.package_class.value
        for pkg in plan.installed()
        if pkg.name in {"numpy", "pydantic-core", "pyyaml", "fastapi"}
    }
    assert kept == {
        "fastapi": "pure_wheel",
        "numpy": "beeware_wheel",
        "pydantic-core": "cross_build",
        "pyyaml": "pure_source",
    }
    assert {"mcp", "cryptography", "rpds-py", "boto3", "botocore"} <= {
        pkg.name for pkg in plan.of(payload.PackageClass.EXCLUDED)
    }


def test_rust_flags_are_appended_to_the_variable_cargo_reads() -> None:
    flags = ["--remap-path-prefix=/a=/x"]
    assert payload.with_rustflags({}, flags) == {"RUSTFLAGS": "--remap-path-prefix=/a=/x"}
    assert payload.with_rustflags({"RUSTFLAGS": "-C debuginfo=0"}, flags) == {
        "RUSTFLAGS": "-C debuginfo=0 --remap-path-prefix=/a=/x"
    }
    assert payload.with_rustflags(
        {"RUSTFLAGS": "ignored", "CARGO_ENCODED_RUSTFLAGS": "-Cdebuginfo=0"}, flags
    ) == {
        "RUSTFLAGS": "ignored",
        "CARGO_ENCODED_RUSTFLAGS": "-Cdebuginfo=0\x1f--remap-path-prefix=/a=/x",
    }


