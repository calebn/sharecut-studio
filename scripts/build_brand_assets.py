#!/usr/bin/env python3
"""Derive the ShareCut symbol, app icon and lockup geometry from the vendored lockup SVGs.

``deploy/brand/logo/logo-dark.svg`` and ``logo-light.svg`` are the approved vector
masters (see ``deploy/brand/logo/PROVENANCE.md``). Nothing here redraws them: the
symbol paths and the outlined wordmark are copied verbatim, only the canvas around
them changes.

    python3 scripts/build_brand_assets.py          # write the derived files
    python3 scripts/build_brand_assets.py --check  # fail when a derived file is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOGO = ROOT / "deploy/brand/logo"
DARK = LOGO / "logo-dark.svg"
LIGHT = LOGO / "logo-light.svg"

APP_ICON = ROOT / "gui/desktop/src-tauri/app-icon.svg"
APP_ICON_COPIES = (
    ROOT / "gui/web/public/favicon.svg",
    ROOT / "gui/desktop/src-tauri/icons/icon.svg",
)
APP_ICON_MACOS = ROOT / "gui/desktop/src-tauri/app-icon-macos.svg"
HOME_SCREEN_ICON = ROOT / "gui/web/public/assets/app/icon.svg"
GEOMETRY_TS = ROOT / "gui/web/src/ui/brand/lockupGeometry.ts"

CANVAS = "#181614"
SYMBOL_BOX = (8, 12, 80, 72)
ICON_SIZE = 1024
LINE_WIDTH = 80
ICON_RADIUS = 224
# The tile is rounded for desktop and favicon use; the maskable symbol must stay inside
# the safe circle (radius 40% of the canvas), so the Home Screen icon draws it smaller.
TILE_SYMBOL_SCALE = 8.0
MASKABLE_SYMBOL_SCALE = 7.2
# macOS draws the icon as given, so the tile sits inside Apple's 824 px grid on the
# 1024 px canvas, with the same proportions as the full-bleed tile.
MACOS_TILE = 824
MACOS_TILE_RADIUS = 185

SYMBOL_PATH = re.compile(r'<path id="([a-z-]+)" fill="(#[0-9a-f]{6})" d="([^"]+)" />')
WORDMARK_PATH = re.compile(r'<path transform="translate\((\d+) 0\)" d="([^"]+)" />')
LOCKUP_VIEWBOX = "20 20 498.385 70.029"
WORDMARK_GROUP = re.compile(
    r'<g xmlns="http://www.w3.org/2000/svg" id="ShareCut"[^>]*transform="([^"]+)"><g transform="([^"]+)">'
)


class Master:
    def __init__(self, path: Path) -> None:
        text = path.read_text(encoding="utf-8")
        self.symbol = SYMBOL_PATH.findall(text)
        self.glyphs = WORDMARK_PATH.findall(text)
        group = WORDMARK_GROUP.search(text)
        if len(self.symbol) != 4 or len(self.glyphs) != 8 or group is None:
            raise SystemExit(f"{path} no longer has the expected symbol and wordmark parts")
        self.wordmark_offset, self.glyph_scale = group.groups()


def symbol_group(master: Master, fills: dict[str, str] | None = None) -> str:
    paths = []
    for ident, fill, d in master.symbol:
        paths.append(f'<path id="{ident}" fill="{(fills or {}).get(fill, fill)}" d="{d}"/>')
    return "".join(paths)


def standalone_symbol(master: Master, fills: dict[str, str] | None = None) -> str:
    x, y, w, h = SYMBOL_BOX
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}" '
        'role="img" aria-label="ShareCut">'
        f'<g id="two-tracks-selected-symbol">{symbol_group(master, fills)}</g></svg>\n'
    )


def app_icon(master: Master, *, rounded: bool, scale: float, inset: bool = False) -> str:
    cx = SYMBOL_BOX[0] + SYMBOL_BOX[2] / 2
    cy = SYMBOL_BOX[1] + SYMBOL_BOX[3] / 2
    radius = f' rx="{ICON_RADIUS}"' if rounded else ""
    half = ICON_SIZE // 2
    tile = f'  <rect width="{ICON_SIZE}" height="{ICON_SIZE}"{radius} fill="{CANVAS}"/>\n'
    if inset:
        edge = (ICON_SIZE - MACOS_TILE) // 2
        tile = (
            f'  <rect x="{edge}" y="{edge}" width="{MACOS_TILE}" height="{MACOS_TILE}" '
            f'rx="{MACOS_TILE_RADIUS}" fill="{CANVAS}"/>\n'
        )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{ICON_SIZE}" height="{ICON_SIZE}" '
        f'viewBox="0 0 {ICON_SIZE} {ICON_SIZE}" fill="none">\n'
        "  <!-- ShareCut app icon: the Two tracks symbol on the dark canvas. Generated by\n"
        "       scripts/build_brand_assets.py from deploy/brand/logo; do not edit by hand. -->\n"
        f"{tile}"
        f'  <g id="two-tracks-selected-symbol" transform="translate({half} {half}) '
        f'scale({scale}) translate(-{cx:g} -{cy:g})">{symbol_group(master)}</g>\n'
        "</svg>\n"
    )


def _const(name: str, value: str) -> str:
    """One string constant, wrapped where Biome wraps it (80 columns)."""
    line = f'export const {name} = "{value}";'
    if len(line) <= LINE_WIDTH:
        return line + "\n"
    return f'export const {name} =\n  "{value}";\n'


def geometry_module(master: Master) -> str:
    symbol = "".join(
        f'  {{\n    id: "{ident}",\n    tone: "{"accent" if idx >= 2 else "ink"}",\n    d: "{d}",\n  }},\n'
        for idx, (ident, _fill, d) in enumerate(master.symbol)
    )
    glyphs = "".join(f'  {{\n    x: {x},\n    d: "{d}",\n  }},\n' for x, d in master.glyphs)
    return (
        "// Generated by scripts/build_brand_assets.py from deploy/brand/logo/logo-dark.svg.\n"
        "// Do not edit: change the vendored master and rerun the script.\n\n"
        + _const("LOCKUP_VIEWBOX", LOCKUP_VIEWBOX)
        + _const("SYMBOL_VIEWBOX", " ".join(str(n) for n in SYMBOL_BOX))
        + _const(
            "LOCKUP_SYMBOL_TRANSFORM",
            "translate(0 0) scale(0.9722222222222222) translate(-8 -12)",
        )
        + _const("LOCKUP_WORDMARK_TRANSFORM", master.wordmark_offset)
        + _const("LOCKUP_GLYPH_TRANSFORM", master.glyph_scale)
        + '\nexport type SymbolTone = "ink" | "accent";\n\n'
        "export const SYMBOL_PATHS: readonly {\n"
        "  readonly id: string;\n  readonly tone: SymbolTone;\n  readonly d: string;\n"
        "}[] = [\n"
        f"{symbol}];\n\n"
        "export const WORDMARK_GLYPHS: readonly {\n"
        "  readonly x: number;\n  readonly d: string;\n"
        "}[] = [\n"
        f"{glyphs}];\n"
    )


def outputs() -> dict[Path, str]:
    dark, light = Master(DARK), Master(LIGHT)
    tile = app_icon(dark, rounded=True, scale=TILE_SYMBOL_SCALE)
    files = {
        LOGO / "symbol-dark.svg": standalone_symbol(dark),
        LOGO / "symbol-light.svg": standalone_symbol(light),
        LOGO / "symbol-mono.svg": standalone_symbol(
            dark, {fill: "currentColor" for _, fill, _ in dark.symbol}
        ),
        APP_ICON: tile,
        APP_ICON_MACOS: app_icon(
            dark,
            rounded=True,
            scale=round(TILE_SYMBOL_SCALE * MACOS_TILE / ICON_SIZE, 3),
            inset=True,
        ),
        HOME_SCREEN_ICON: app_icon(dark, rounded=False, scale=MASKABLE_SYMBOL_SCALE),
        GEOMETRY_TS: geometry_module(dark),
    }
    files.update({copy: tile for copy in APP_ICON_COPIES})
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a derived file is stale")
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    for path in stale:
        print(f"{'stale' if args.check else 'wrote'}: {path.relative_to(ROOT)}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
