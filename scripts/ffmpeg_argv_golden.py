#!/usr/bin/env python3
"""Record the argv, output hashes and loudness values of a fixed set of FFmpegEngine operations (#1815).

Run it on two trees and ``--compare`` the files: an ffmpeg package split must not change one byte
of any argv or output. The audio is generated by the engine itself, so nothing is committed.

    python scripts/ffmpeg_argv_golden.py -o before.json
    python scripts/ffmpeg_argv_golden.py -o after.json
    python scripts/ffmpeg_argv_golden.py --compare before.json after.json
"""

from __future__ import annotations

import argparse
import dataclasses
import difflib
import hashlib
import importlib
import json
import sys
import tempfile
from collections.abc import Callable, Iterator, Sequence
from contextlib import ExitStack, contextmanager
from enum import Enum
from pathlib import Path
from types import ModuleType
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np

from podcast_mcp.engines.audio import At, MixAudio, SequenceAudio, SourceAudio
from podcast_mcp.engines.ffmpeg import FFmpegEngine

WORK_TOKEN = "<work>"
OWNER_MODULES = ("podcast_mcp.engines.ffmpeg.runtime", "podcast_mcp.engines.ffmpeg")
SPAWNERS = ("run", "popen")


def owner_module() -> ModuleType:
    """The module whose ``run`` and ``popen`` the engine calls: the runtime module once it exists."""
    for name in OWNER_MODULES:
        try:
            module = importlib.import_module(name)
        except ModuleNotFoundError:
            continue
        if all(hasattr(module, spawner) for spawner in SPAWNERS):
            return module
    raise RuntimeError(f"no module among {OWNER_MODULES} defines {SPAWNERS}")


class ArgvRecorder:
    """Wraps the owner module's ``run`` and ``popen`` and keeps every argv they were given."""

    def __init__(self, module: ModuleType) -> None:
        self.module = module
        self.argvs: list[list[str]] = []

    def _wrap(self, real: Callable[..., Any]) -> Callable[..., Any]:
        def recorded(argv: Sequence[Any], *args: Any, **kwargs: Any) -> Any:
            self.argvs.append([str(part) for part in argv])
            return real(argv, *args, **kwargs)

        return recorded

    @contextmanager
    def recording(self) -> Iterator[None]:
        originals = {name: getattr(self.module, name) for name in SPAWNERS}
        try:
            for name, real in originals.items():
                setattr(self.module, name, self._wrap(real))
            yield
        finally:
            for name, real in originals.items():
                setattr(self.module, name, real)

    def take(self) -> list[list[str]]:
        taken, self.argvs = self.argvs, []
        return taken


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def normalize(value: Any, engine: FFmpegEngine, work: Path) -> Any:
    """The value with the work directory and the binary paths replaced, so two runs compare equal."""
    roots = sorted({str(work), str(work.resolve())}, key=len, reverse=True)
    binaries = {engine.ffmpeg: "<ffmpeg>", engine.ffprobe: "<ffprobe>"}

    def walk(item: Any, *, head: bool = False) -> Any:
        if isinstance(item, str):
            if head and item in binaries:
                return binaries[item]
            for root in roots:
                item = item.replace(root, WORK_TOKEN)
            return item
        if isinstance(item, dict):
            return {
                walk(key): [walk(argv, head=True) for argv in val] if key == "argv" else walk(val)
                for key, val in item.items()
            }
        if isinstance(item, list):
            return [walk(part, head=head and index == 0) for index, part in enumerate(item)]
        return item

    return walk(value)


def plain(value: Any) -> Any:
    """A JSON form of a result: arrays by hash, paths as strings, dataclasses as dicts."""
    if isinstance(value, np.ndarray):
        return {
            "shape": list(value.shape),
            "dtype": str(value.dtype),
            "sha256": hashlib.sha256(value.tobytes()).hexdigest(),
        }
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        return {f.name: plain(getattr(value, f.name)) for f in dataclasses.fields(value)}
    if isinstance(value, dict):
        return {str(key): plain(val) for key, val in value.items()}
    if isinstance(value, (list, tuple)):
        return [plain(part) for part in value]
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, Enum):
        return str(value.value)
    return value


class Suite:
    def __init__(self, engine: FFmpegEngine, work: Path, recorder: ArgvRecorder) -> None:
        self.engine = engine
        self.work = work
        self.recorder = recorder
        self.steps: dict[str, dict[str, Any]] = {}
        self.tone_a = work / "tone_a.wav"
        self.tone_b = work / "tone_b.wav"
        self.hush = work / "hush.wav"

    def record(self, name: str, result: Any = None, outputs: Sequence[Path] = ()) -> None:
        self.steps[name] = {
            "argv": self.recorder.take(),
            "outputs": {path.name: sha256_of(path) for path in outputs},
            "result": plain(result),
        }

    def out(self, name: str) -> Path:
        return self.work / name

    def setup(self) -> None:
        eng = self.engine
        eng.generate_tone(self.tone_a, duration_sec=2.0, freq_hz=220.0)
        eng.generate_tone(self.tone_b, duration_sec=2.0, freq_hz=330.0, gain_db=-6.0)
        self.record("generate_tone", outputs=[self.tone_a, self.tone_b])
        eng.silence(self.hush, 0.5, sample_rate=48000, channels=1)
        self.record("silence", outputs=[self.hush])

    def probe(self) -> None:
        self.record("probe", self.engine.probe(self.tone_a))
        self.record("astats", self.engine.astats(self.tone_a, ffmpeg=self.engine.ffmpeg))

    def decode(self) -> None:
        eng = self.engine
        self.record(
            "decode_full_f32",
            eng.decode_full_f32(self.tone_a, sample_rate=48000, layout=["-ac", "1"]),
        )
        rate, channels, chunks = eng.stream_pcm_f32(self.tone_a, chunk_frames=30000)
        pcm = np.concatenate(list(chunks))
        self.record("stream_pcm_f32", {"rate": rate, "channels": channels, "pcm": pcm})
        self.record("decode_window_f32", eng.decode_window_f32(self.tone_a, 12000, 20000, 48000, 1))
        flac = self.out("encoded.flac")
        eng.encode_flac_f32([pcm[:40000], pcm[40000:]], flac, sample_rate=rate, channels=channels)
        self.record("encode_flac_f32", outputs=[flac])

    def render(self) -> None:
        eng = self.engine
        chain = SequenceAudio(
            SourceAudio(self.tone_a, 0.0, 1.0, fade_out_sec=0.1),
            (SourceAudio(self.tone_b, 0.5, 1.5, fade_in_sec=0.1, gain_db=-3.0),),
        )
        sequence = eng.render_timeline(self.out("timeline_sequence.wav"), chain, "highpass=f=80")
        self.record("render_timeline_sequence", outputs=[sequence])
        layered = MixAudio(
            At(0.0, SourceAudio(self.tone_a, 0.0, 1.0)),
            (At(0.5, SourceAudio(self.tone_b, 0.0, 1.0)),),
        )
        mixed = eng.render_timeline(
            self.out("timeline_mix.wav"), layered, "acompressor=threshold=-18dB"
        )
        self.record("render_timeline_mix", outputs=[mixed])

    def assemble(self) -> None:
        eng = self.engine
        tracks = [(self.tone_a, 0.0), (self.tone_b, -4.0)]
        mixed = eng.mix_tracks(tracks, self.out("mix.wav"))
        self.record("mix_tracks", outputs=[mixed])
        ceiling = eng.mix_tracks(tracks, self.out("mix_ceiling.wav"), peak_ceiling_db=-6.0)
        self.record("mix_tracks_peak_ceiling", outputs=[ceiling])
        self.record("mix_peak_db", eng.mix_peak_db(tracks, -1.0))
        joined = eng.join_audio_parts(
            [self.tone_a, self.tone_b, self.tone_a],
            self.out("join.wav"),
            crossfade_ms_between=[50, 0],
        )
        self.record("join_audio_parts", outputs=[joined])
        gapped = eng.concat_with_gap(
            self.tone_a, self.tone_b, self.out("gap.wav"), gap_sec=0.25, rate=48000, channels=1
        )
        self.record("concat_with_gap", outputs=[gapped])
        padded = eng.pad_end_silence(self.tone_a, self.out("padded.wav"), 3.0)
        self.record("pad_end_silence", outputs=[padded])
        gained = eng.apply_gain(self.tone_a, self.out("gain.wav"), -9.0)
        self.record("apply_gain", outputs=[gained])
        filtered = eng.filter_audio(self.tone_a, self.out("filtered.wav"), "lowpass=f=1000")
        self.record("filter_audio", outputs=[filtered])
        segment = eng.extract_segment(
            self.tone_a, self.out("segment.wav"), 0.25, 1.25, gain_db=-2.0
        )
        self.record("extract_segment", outputs=[segment])

    def loudness(self) -> None:
        eng = self.engine
        self.record("measure_loudness", eng.measure_loudness(self.tone_a))
        self.record("measure_loudness_full", eng.measure_loudness_full(self.tone_a))
        self.record("measure_loudness_screen", eng.measure_loudness_screen(self.tone_a))
        self.record("measure_loudness_blocks", eng.measure_loudness_blocks(self.tone_a))
        self.record("loudnorm_input_stats", eng.loudnorm_input_stats(self.tone_a))
        mastered = self.out("master.wav")
        self.record(
            "master_loudness", eng.master_loudness(self.tone_a, mastered), outputs=[mastered]
        )

    def export(self) -> None:
        eng = self.engine
        wav = eng.export_audio(
            self.tone_a, self.out("export.wav"), codec="pcm_s16le", sample_rate=44100
        )
        self.record("export_wav", outputs=[wav])
        mp3 = eng.export_audio(
            self.tone_a,
            self.out("export.mp3"),
            codec="libmp3lame",
            bitrate_kbps=96,
            metadata={"title": "golden"},
        )
        self.record("export_mp3", outputs=[mp3])
        flac = eng.export_audio(self.tone_a, self.out("export.flac"), codec="flac")
        self.record("export_flac", outputs=[flac])
        self.record(
            "export_mp3_helper", outputs=[eng.export_mp3(self.tone_a, self.out("helper.mp3"))]
        )

    def images(self) -> None:
        eng = self.engine
        spectrogram = eng.render_spectrogram(
            self.tone_a, self.out("spectrogram.png"), size="320x160"
        )
        self.record("render_spectrogram", outputs=[spectrogram])
        wave = eng.render_showwavespic(self.tone_a, self.out("wave.png"), size="320x80")
        self.record("render_showwavespic", outputs=[wave])


STEPS = ("probe", "decode", "render", "assemble", "loudness", "export", "images")


def run_suite(
    engine: FFmpegEngine, work: Path, only: Sequence[str] | None = None
) -> dict[str, Any]:
    """Drive the operations in ``work`` and return their normalized record; ``only`` names a subset of ``STEPS``."""
    unknown = set(only or ()) - set(STEPS)
    if unknown:
        raise ValueError(f"unknown steps {sorted(unknown)}; choose from {STEPS}")
    recorder = ArgvRecorder(owner_module())
    suite = Suite(engine, work, recorder)
    with ExitStack() as stack:
        stack.enter_context(recorder.recording())
        suite.setup()
        for step in STEPS:
            if only is None or step in only:
                getattr(suite, step)()
    return normalize(
        {"owner": recorder.module.__name__.rsplit(".", 1)[-1], "steps": suite.steps}, engine, work
    )


def render_json(record: dict[str, Any]) -> str:
    return json.dumps(record, indent=2, sort_keys=True) + "\n"


def compare_texts(left: str, right: str, left_name: str = "a", right_name: str = "b") -> str:
    """A unified diff of two JSON texts; empty when they are identical."""
    return "".join(
        difflib.unified_diff(
            left.splitlines(keepends=True),
            right.splitlines(keepends=True),
            fromfile=left_name,
            tofile=right_name,
        )
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("-o", "--output", type=Path, help="write the JSON here (default: stdout)")
    parser.add_argument("--only", nargs="+", choices=STEPS, help="drive only these steps")
    parser.add_argument(
        "--compare", nargs=2, type=Path, metavar=("A", "B"), help="diff two recorded files"
    )
    args = parser.parse_args(argv)
    if args.compare:
        left, right = args.compare
        diff = compare_texts(
            left.read_text(encoding="utf-8"),
            right.read_text(encoding="utf-8"),
            str(left),
            str(right),
        )
        sys.stdout.write(diff)
        return 1 if diff else 0
    engine = FFmpegEngine()
    available, detail = engine.check_available()
    if not available:
        sys.stderr.write(f"ffmpeg is not available: {detail}\n")
        return 2
    with tempfile.TemporaryDirectory(prefix="ffmpeg-golden-") as directory:
        text = render_json(run_suite(engine, Path(directory), args.only))
    if args.output:
        args.output.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
