#!/usr/bin/env python3
"""Record what a fixed set of FFmpegEngine operations spawn and write (#1815).

For every spawn it records the argv, the sorted keyword names and the repr of the non-callable
keyword values (``timeout``, ``check``, ``capture_output``, ``stdin``, ``stdout``, the length of
``input``). For every step it records the sha256 of each output file and the result. Spawns are
caught at the one seam all of them pass through: every binding of ``util.process.run`` and
``util.process.popen`` in a ``podcast_mcp`` module, so the module layout of the engine does not
matter. Not caught: a spawn that bypasses those two functions, or a binding held in a container.

Covered: probe, astats, the PCM decode and encode helpers, resample_streams, render_timeline and
render_dialogue_track, mix and join helpers, loudness measures, export (plain and cancellable,
including a cancel that trips), spectrogram, waveform images and annotate_time_marks,
check_available, check_ffprobe_version and supports_encode. Not covered: the progress-callback
variants, the untrusted probe, and error paths other than the cancel.

Run it on two trees and ``--compare`` the files: a refactor of the engine must not change one
byte of any of that. The audio is generated by the engine itself, so nothing is committed.

    python scripts/ffmpeg_argv_golden.py -o before.json
    python scripts/ffmpeg_argv_golden.py -o after.json
    python scripts/ffmpeg_argv_golden.py --compare before.json after.json
"""

